<script setup lang="ts">
import { 
  Building2, 
  Calendar, 
  Download, 
  Eye, 
  FileText, 
  Filter, 
  Plus, 
  RotateCcw, 
  Search 
} from 'lucide-vue-next'

definePageMeta({ layout: 'admin', middleware: 'admin-auth', requiredPermission: ['quotes.view', 'services.view', 'orders.view'] })

const { t, locale } = useI18n()
const localePath = useLocalePath()
const route = useRoute()
const router = useRouter()

const search = ref(String(route.query.search || ''))
const status = ref(String(route.query.status || ''))
const page = ref(Number(route.query.page) || 1)
const limit = 20

interface QuoteRow {
  id: string
  quoteNumber: string
  companyName: string
  contactName: string
  phone: string
  email: string | null
  totalAmount: number
  status: string
  pdfPath: string | null
  createdAt: string
  _count: { items: number }
}

const fetch = useRequestFetch()

const { data, refresh, pending } = await useAsyncData('admin-quotes', () =>
  fetch<{ quotes: QuoteRow[], total: number, pages: number }>(`/api/admin/quotes?${new URLSearchParams({
    search: search.value,
    status: status.value,
    page: String(page.value),
    limit: String(limit),
  })}`),
  { watch: [page] },
)

const hasFilters = computed(() => !!(search.value || status.value))

async function applyFilters() {
  page.value = 1
  await router.replace({
    query: {
      search: search.value || undefined,
      status: status.value || undefined,
    },
  })
  await refresh()
}

async function resetFilters() {
  search.value = ''
  status.value = ''
  page.value = 1
  await router.replace({ query: {} })
  await refresh()
}

function formatDate(d: string) {
  return new Date(d).toLocaleDateString(locale.value === 'ar' ? 'ar-EG' : 'en-US', {
    year: 'numeric',
    month: 'short',
    day: 'numeric',
    hour: '2-digit',
    minute: '2-digit',
  })
}

async function gotoPage(p: number) {
  page.value = p
  await router.replace({
    query: {
      search: search.value || undefined,
      status: status.value || undefined,
      page: p > 1 ? String(p) : undefined,
    },
  })
}
</script>

<template>
  <div>
    <!-- Page Header -->
    <AdminPageHeader
      :title="locale === 'ar' ? 'طلبات عروض الأسعار' : 'Quote Requests'"
      :description="locale === 'ar' ? 'متابعة عروض الأسعار المستخرجة من قبل الشركات والمهندسين وتحميل ملفات الـ PDF.' : 'Monitor B2B price quotations generated by clients and access official PDF documents.'"
    >
      <template #actions>
        <NuxtLink
          :to="localePath('/admin/quotes/new')"
          class="inline-flex h-10 items-center gap-1.5 rounded-md bg-[#2B71AE] px-4 text-xs font-semibold text-white shadow-xs transition-colors hover:bg-[#285E8E] focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-[#2B71AE]"
        >
          <Plus class="h-4 w-4" aria-hidden="true" />
          <span>{{ locale === 'ar' ? 'إنشاء عرض سعر' : 'Create Quote' }}</span>
        </NuxtLink>
      </template>
    </AdminPageHeader>

    <!-- Filter Toolbar -->
    <div
      class="mb-4 rounded-md border bg-white p-3.5 shadow-xs dark:bg-[#162032]"
      :style="{ borderColor: 'var(--color-border)' }"
    >
      <form class="flex flex-wrap items-center gap-2.5" @submit.prevent="applyFilters">
        <!-- Search Input -->
        <div class="relative min-w-48 flex-1 sm:min-w-64">
          <Search class="pointer-events-none absolute start-3 top-1/2 h-4 w-4 -translate-y-1/2 text-slate-400" aria-hidden="true" />
          <input
            v-model="search"
            type="search"
            :placeholder="locale === 'ar' ? 'بحث برقم العرض، اسم الشركة، المسؤول، الهاتف…' : 'Search by quote #, company, contact, phone…'"
            class="h-9 w-full rounded-md border bg-white ps-9 pe-3 text-xs placeholder:text-slate-400 focus:border-[#2B71AE] focus:outline-none focus:ring-2 focus:ring-[#2B71AE]/20 dark:bg-[#0B1520]"
            :style="{ borderColor: 'var(--color-border)' }"
          />
        </div>

        <!-- Status Filter -->
        <select
          v-model="status"
          class="h-9 rounded-md border bg-white px-3 text-xs text-slate-700 focus:border-[#2B71AE] focus:outline-none focus:ring-2 focus:ring-[#2B71AE]/20 dark:bg-[#0B1520] dark:text-slate-300"
          :style="{ borderColor: 'var(--color-border)' }"
          @change="applyFilters"
        >
          <option value="">{{ locale === 'ar' ? 'جميع الحالات' : 'All Statuses' }}</option>
          <option value="New">{{ locale === 'ar' ? 'جديد (New)' : 'New' }}</option>
          <option value="Reviewed">{{ locale === 'ar' ? 'تمت المراجعة (Reviewed)' : 'Reviewed' }}</option>
          <option value="Closed">{{ locale === 'ar' ? 'مغلق (Closed)' : 'Closed' }}</option>
        </select>

        <!-- Apply Button -->
        <button
          type="submit"
          class="inline-flex h-9 items-center gap-1.5 rounded-md border border-slate-200 bg-slate-50 px-3.5 text-xs font-semibold text-slate-700 transition-colors hover:bg-slate-100 hover:text-slate-900 dark:border-slate-700 dark:bg-slate-800 dark:text-slate-300 dark:hover:bg-slate-700"
        >
          <Filter class="h-3.5 w-3.5" aria-hidden="true" />
          <span>{{ locale === 'ar' ? 'تصفية' : 'Filter' }}</span>
        </button>

        <!-- Reset Button -->
        <button
          v-if="hasFilters"
          type="button"
          class="inline-flex h-9 items-center gap-1.5 rounded-md px-2.5 text-xs font-medium text-slate-500 hover:text-slate-800 dark:hover:text-slate-200"
          @click="resetFilters"
        >
          <RotateCcw class="h-3.5 w-3.5" aria-hidden="true" />
          <span>{{ locale === 'ar' ? 'إلغاء' : 'Reset' }}</span>
        </button>
      </form>
    </div>

    <!-- Quotes Table Card -->
    <div class="overflow-hidden rounded-md border bg-white shadow-xs dark:bg-[#162032]" :style="{ borderColor: 'var(--color-border)' }">
      <div class="overflow-x-auto">
        <table class="w-full min-w-[860px] text-start text-sm">
          <thead class="sticky top-0 z-10">
            <tr class="border-b bg-slate-50/75 text-[11px] font-semibold uppercase tracking-wider text-slate-500 dark:bg-slate-800/40 dark:text-slate-400" :style="{ borderColor: 'var(--color-border)' }">
              <th scope="col" class="px-4 py-3 text-start">{{ locale === 'ar' ? 'رقم العرض' : 'Quote #' }}</th>
              <th scope="col" class="px-4 py-3 text-start">{{ locale === 'ar' ? 'الشركة / المنشأة' : 'Company' }}</th>
              <th scope="col" class="px-4 py-3 text-start">{{ locale === 'ar' ? 'المسؤول' : 'Contact Person' }}</th>
              <th scope="col" class="px-4 py-3 text-start">{{ locale === 'ar' ? 'تاريخ الإنشاء' : 'Date' }}</th>
              <th scope="col" class="px-4 py-3 text-start">{{ locale === 'ar' ? 'الإجمالي' : 'Total' }}</th>
              <th scope="col" class="px-4 py-3 text-center">{{ locale === 'ar' ? 'الحالة' : 'Status' }}</th>
              <th scope="col" class="px-4 py-3 text-end">{{ locale === 'ar' ? 'الإجراءات' : 'Actions' }}</th>
            </tr>
          </thead>
          <tbody class="divide-y divide-slate-100 dark:divide-slate-800/60">
            <tr
              v-for="q in data?.quotes || []"
              :key="q.id"
              class="transition-colors even:bg-slate-50/50 even:dark:bg-slate-800/30 hover:bg-slate-50/60 dark:hover:bg-slate-800/40"
            >
              <!-- Quote Number -->
              <td class="px-4 py-3 font-medium">
                <NuxtLink
                  :to="localePath(`/admin/quotes/${q.id}`)"
                  class="font-mono text-xs font-bold text-[#2B71AE] hover:underline dark:text-blue-400"
                >
                  {{ q.quoteNumber }}
                </NuxtLink>
              </td>

              <!-- Company -->
              <td class="px-4 py-3">
                <div class="flex items-center gap-2">
                  <Building2 class="h-3.5 w-3.5 text-slate-400 shrink-0" />
                  <span class="font-semibold text-slate-900 dark:text-slate-100">{{ q.companyName }}</span>
                </div>
              </td>

              <!-- Contact Person & Phone -->
              <td class="px-4 py-3">
                <div>
                  <p class="font-semibold text-slate-900 dark:text-slate-100">{{ q.contactName }}</p>
                  <p class="font-mono text-xs text-slate-500 dark:text-slate-400" dir="ltr">{{ q.phone }}</p>
                </div>
              </td>

              <!-- Date -->
              <td class="px-4 py-3 text-xs text-slate-500 dark:text-slate-400">
                {{ formatDate(q.createdAt) }}
              </td>

              <!-- Total & Items Count -->
              <td class="px-4 py-3">
                <div class="flex items-baseline gap-1">
                  <span class="font-bold text-slate-900 dark:text-slate-100">{{ Number(q.totalAmount).toLocaleString() }}</span>
                  <span class="text-xs text-slate-500">EGP</span>
                  <span class="ms-1 rounded bg-slate-100 px-1.5 py-0.2 text-[10px] text-slate-600 dark:bg-slate-800 dark:text-slate-400">
                    {{ q._count?.items || 1 }} {{ locale === 'ar' ? 'منتج' : 'items' }}
                  </span>
                </div>
              </td>

              <!-- Status Badge -->
              <td class="px-4 py-3 text-center">
                <AdminStatusBadge :status="q.status" size="sm" />
              </td>

              <!-- Actions: Details & Download PDF -->
              <td class="px-4 py-3 text-end">
                <div class="flex items-center justify-end gap-1.5">
                  <NuxtLink
                    :to="localePath(`/admin/quotes/${q.id}`)"
                    class="inline-flex h-8 items-center gap-1 rounded px-2.5 text-xs font-semibold text-[#2B71AE] transition-colors hover:bg-[#2B71AE]/10 dark:text-blue-400 dark:hover:bg-blue-950/50"
                  >
                    <Eye class="h-3.5 w-3.5" aria-hidden="true" />
                    <span>{{ locale === 'ar' ? 'تفاصيل' : 'Details' }}</span>
                  </NuxtLink>

                  <a
                    :href="`/api/quotes/${q.id}/pdf?locale=en`"
                    target="_blank"
                    download
                    class="inline-flex h-8 items-center gap-1 rounded border border-slate-200 px-2 text-xs font-semibold text-slate-700 hover:bg-slate-50 dark:border-slate-700 dark:text-slate-300 dark:hover:bg-slate-800"
                    title="Download English PDF"
                  >
                    <Download class="h-3 w-3" />
                    <span>EN</span>
                  </a>
                  <a
                    :href="`/api/quotes/${q.id}/pdf?locale=ar`"
                    target="_blank"
                    download
                    class="inline-flex h-8 items-center gap-1 rounded bg-[#2B71AE]/10 px-2 text-xs font-semibold text-[#2B71AE] hover:bg-[#2B71AE]/20 dark:bg-[#F5CC07]/15 dark:text-[#F5CC07]"
                    title="تحميل PDF عربي"
                  >
                    <Download class="h-3 w-3" />
                    <span>عربي</span>
                  </a>
                </div>
              </td>
            </tr>
          </tbody>
        </table>
      </div>

      <!-- Empty State -->
      <div v-if="!data?.quotes?.length" class="p-8">
        <AdminEmptyState
          :title="hasFilters ? (locale === 'ar' ? 'لا توجد عروض أسعار مطابقة للبحث' : 'No quotes matching filters') : (locale === 'ar' ? 'لا توجد طلبات عروض أسعار مسجلة حتى الآن' : 'No quote requests yet')"
          :description="hasFilters ? (locale === 'ar' ? 'جرب البحث بمعايير أخرى أو إعادة ضبط الفلاتر.' : 'Try changing status or search terms.') : (locale === 'ar' ? 'ستظهر هنا عروض الأسعار المستخرجة من قبل عملاء المتجر والشركات.' : 'B2B price quotation requests created by customers will appear here.')"
          :icon="FileText"
        >
          <template #action>
            <button
              v-if="hasFilters"
              type="button"
              class="inline-flex h-9 items-center gap-1.5 rounded-md border px-3 text-xs font-semibold text-slate-700 hover:bg-slate-50 dark:border-slate-700 dark:text-slate-300"
              @click="resetFilters"
            >
              <RotateCcw class="h-3.5 w-3.5" aria-hidden="true" />
              <span>{{ locale === 'ar' ? 'إعادة ضبط الفلاتر' : 'Reset filters' }}</span>
            </button>
          </template>
        </AdminEmptyState>
      </div>

      <!-- Pagination -->
      <AdminPagination
        :page="page"
        :pages="data?.pages || 1"
        :total="data?.total || 0"
        :item-name="locale === 'ar' ? 'عرض سعر' : 'quotes'"
        @change="gotoPage"
      />
    </div>
  </div>
</template>
